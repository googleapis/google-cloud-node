'use strict'
const helper = require('../../test-helper.cjs')
const assert = require('assert')
const suite = new helper.Suite()

suite.test('huge numeric custom type parser', function (done) {
  const pool = new helper.pg.Pool()
  pool.connect(
    assert.success(function (client, poolDone) {
      const types = helper.pg.types
      // 1700 = NUMERIC OID (Spanner PG parses custom type parser via text representation)
      types.setTypeParser(1700, function () {
        return 'yes'
      })
      const bignum = '294733346389144765940638005275'
      client.query('CREATE TABLE IF NOT EXISTS bignumz(spanner_pk_id BIGINT GENERATED BY DEFAULT AS IDENTITY (BIT_REVERSED_POSITIVE) PRIMARY KEY, id numeric)', function (err) {
        assert.ifError(err)
        client.query('DELETE FROM bignumz', function (err) {
          assert.ifError(err)
          client.query('INSERT INTO bignumz(id) VALUES ($1::numeric)', [bignum], function (err) {
            assert.ifError(err)
            client.query(
              'SELECT * FROM bignumz',
              assert.success(function (result) {
                assert.equal(result.rows[0].id, 'yes')
                poolDone()
                pool.end(done)
              })
            )
          })
        })
      })
    })
  )
})
