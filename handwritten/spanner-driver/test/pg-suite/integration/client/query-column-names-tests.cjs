'use strict'
const helper = require('../../test-helper.cjs')
const pg = helper.pg
const assert = require('assert')

new helper.Suite().test('support for complex column names', function () {
  const pool = new pg.Pool()
  pool.connect(
    assert.success(function (client, done) {
      client.query('CREATE TABLE IF NOT EXISTS t(spanner_pk_id BIGINT GENERATED BY DEFAULT AS IDENTITY (BIT_REVERSED_POSITIVE) PRIMARY KEY, "complex\'\'column" TEXT)', function (err) {
        assert.ifError(err)
        client.query(
          'SELECT * FROM t',
          assert.success(function (res) {
            done()
            assert.strictEqual(res.fields[0].name, "complex''column")
            pool.end()
          })
        )
      })
    })
  )
})
