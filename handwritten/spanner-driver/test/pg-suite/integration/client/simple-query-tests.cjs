'use strict'
const helper = require('../../test-helper.cjs')
const Query = helper.pg.Query
const assert = require('assert')
const suite = new helper.Suite()
const test = suite.test.bind(suite)

test('simple query interface', async function () {
  console.log('  [step 1/4] Connecting & creating person table...')
  const client = helper.client()
  await helper.createPersonTable(client)
  console.log('  [step 1/4] Table ready. Executing SELECT query...')

  return new Promise((resolve, reject) => {
    const query = client.query(new Query('select name from person order by name'))

    const rows = []
    query.on('row', function (row, result) {
      assert.ok(result)
      rows.push(row['name'])
    })
    query.once('row', function (row) {
      assert.deepStrictEqual(row, { name: row.name })
    })

    query.on('error', function (err) {
      console.error('  [step 1/4] Query error:', err)
      reject(err)
    })

    query.on('end', function () {
      console.log('  [step 1/4] Query end. Total rows:', rows.length)
      assert.lengthIs(rows, 26)
      assert.equal(rows[0], 'Aaron')
      assert.equal(rows[25], 'Zanzabar')
      client.end(resolve)
    })
  })
})

test('prepared statements do not mutate params', async function () {
  console.log('  [step 2/4] Connecting & creating person table for prepared statements...')
  const client = helper.client()
  await helper.createPersonTable(client)
  console.log('  [step 2/4] Executing parameterized SELECT...')

  return new Promise((resolve, reject) => {
    const params = [1]

    const query = client.query(new Query('select name from person where $1 = 1 order by name', params))

    assert.deepEqual(params, [1])

    const rows = []
    query.on('row', function (row, result) {
      assert.ok(result)
      rows.push(row)
    })

    query.on('error', function (err) {
      console.error('  [step 2/4] Query error:', err)
      reject(err)
    })

    query.on('end', function (result) {
      console.log('  [step 2/4] Query end. Total rows:', rows.length)
      assert.lengthIs(rows, 26, 'result returned wrong number of rows')
      assert.lengthIs(rows, result.rowCount)
      assert.equal(rows[0].name, 'Aaron')
      assert.equal(rows[25].name, 'Zanzabar')
      client.end(resolve)
    })
  })
})

test('multiple simple queries', function (done) {
  console.log('  [step 3/4] Creating bang table...')
  const client = helper.client()
  client.query("CREATE TABLE IF NOT EXISTS bang(spanner_pk_id BIGINT GENERATED BY DEFAULT AS IDENTITY (BIT_REVERSED_POSITIVE) PRIMARY KEY, id BIGINT, name varchar(5));", function (err) {
    assert.ifError(err)
    console.log('  [step 3/4] Bang table created. Inserting rows...')
    client.query('DELETE FROM bang WHERE 1=1', function (err) {
      assert.ifError(err)
      client.query("insert into bang(name) VALUES('boom');", function (err) {
        assert.ifError(err)
        client.query("insert into bang(name) VALUES ('yes');", function (err) {
          assert.ifError(err)
          console.log('  [step 3/4] Executing SELECT on bang...')
          const query = client.query(new Query('select name from bang order by name'))
          const rows = []
          query.on('row', function (row) {
            rows.push(row.name)
          })
          query.on('end', function () {
            console.log('  [step 3/4] Bang query end. Rows:', rows.length)
            assert.equal(rows[0], 'boom')
            assert.equal(rows[1], 'yes')
            client.end(done)
          })
        })
      })
    })
  })
})

test('multiple select statements', function (done) {
  console.log('  [step 4/4] Creating boom_select_test & bang_select_test tables...')
  const client = helper.client()
  client.query('CREATE TABLE IF NOT EXISTS boom_select_test(spanner_pk_id BIGINT GENERATED BY DEFAULT AS IDENTITY (BIT_REVERSED_POSITIVE) PRIMARY KEY, age integer);', function (err) {
    assert.ifError(err)
    client.query('CREATE TABLE IF NOT EXISTS bang_select_test(spanner_pk_id BIGINT GENERATED BY DEFAULT AS IDENTITY (BIT_REVERSED_POSITIVE) PRIMARY KEY, name varchar(5));', function (err) {
      assert.ifError(err)
      console.log('  [step 4/4] Tables created. Cleaning up & inserting rows...')
      client.query('DELETE FROM boom_select_test WHERE 1=1', function (err) {
        assert.ifError(err)
        client.query('DELETE FROM bang_select_test WHERE 1=1', function (err) {
          assert.ifError(err)
          client.query('insert into boom_select_test(age) values(1);', function (err) {
            assert.ifError(err)
            client.query("insert into bang_select_test(name) values('zoom');", function (err) {
              assert.ifError(err)
              console.log('  [step 4/4] Executing nested SELECT queries...')
              client.query('select age from boom_select_test where age < 2', function (err, res1) {
                assert.ifError(err)
                assert.equal(res1.rows[0].age, 1)
                client.query('select name from bang_select_test', function (err, res2) {
                  assert.ifError(err)
                  assert.strictEqual(res2.rows[0].name, 'zoom')
                  console.log('  [step 4/4] All queries done!')
                  client.end(done)
                })
              })
            })
          })
        })
      })
    })
  })
})
