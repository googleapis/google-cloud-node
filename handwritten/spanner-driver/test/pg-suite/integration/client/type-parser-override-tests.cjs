'use strict'
const helper = require('../../test-helper.cjs')
const assert = require('assert')
const suite = new helper.Suite()

function testTypeParser(client, expectedResult, done) {
  const boolValue = true
  client.query('CREATE TABLE IF NOT EXISTS parserOverrideTest(spanner_pk_id BIGINT GENERATED BY DEFAULT AS IDENTITY (BIT_REVERSED_POSITIVE) PRIMARY KEY, id bool)', function (err) {
    assert.ifError(err)
    client.query('DELETE FROM parserOverrideTest', function (err) {
      assert.ifError(err)
      client.query('INSERT INTO parserOverrideTest(id) VALUES ($1)', [boolValue], function (err) {
        assert.ifError(err)
        client.query(
          'SELECT * FROM parserOverrideTest',
          assert.success(function (result) {
            assert.equal(result.rows[0].id, expectedResult)
            done()
          })
        )
      })
    })
  })
}

suite.test('type parser override per client', (cb) => {
  const pool = new helper.pg.Pool()
  pool.connect(
    assert.success(function (client1, done1) {
      pool.connect(
        assert.success(function (client2, done2) {
          const boolTypeOID = 16
          client1.setTypeParser(boolTypeOID, function () {
            return 'first client'
          })
          client2.setTypeParser(boolTypeOID, function () {
            return 'second client'
          })

          testTypeParser(client1, 'first client', () => {
            done1()
            testTypeParser(client2, 'second client', () => {
              done2()
              pool.end(cb)
            })
          })
        })
      )
    })
  )
})
