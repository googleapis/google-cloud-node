'use strict'
const helper = require('../../test-helper.cjs')
const pg = helper.pg
const suite = new helper.Suite()
const assert = require('assert')

const testForTypeCoercion = function (type) {
  const pool = new pg.Pool()
  suite.test(`test type coercion ${type.name}`, (cb) => {
    pool.connect(function (err, client, done) {
      assert(!err)
      let castType = type.name
      if (castType.startsWith('varchar')) castType = 'varchar'
      else if (castType === 'smallint') castType = 'integer'
      else if (castType === 'oid') castType = 'bigint'
      else if (castType === 'timestamptz') castType = 'text::timestamptz'

      let pending = type.values.length
      if (pending === 0) {
        done()
        return pool.end(cb)
      }

      type.values.forEach(function (val) {
        client.query('SELECT $1::' + castType + ' AS col', [val], function (err, res) {
          assert(!err)
          if (val !== null && type.name !== 'real' && type.name !== 'double precision') {
            assert.equal(res.rows[0].col, val)
          }
          pending--
          if (pending === 0) {
            done()
            pool.end(cb)
          }
        })
      })
    })
  })
}

