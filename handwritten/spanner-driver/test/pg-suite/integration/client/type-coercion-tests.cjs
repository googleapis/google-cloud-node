suite.test('timestamptz round trip', function (cb) {
  const now = new Date()
  const client = helper.client()
  client.query('CREATE TABLE IF NOT EXISTS date_tests(spanner_pk_id BIGINT GENERATED BY DEFAULT AS IDENTITY (BIT_REVERSED_POSITIVE) PRIMARY KEY, name varchar(10), tstz timestamptz)', function (err) {
    assert.ifError(err)
    client.query('DELETE FROM date_tests', function (err) {
      assert.ifError(err)
      client.query('insert into date_tests(name, tstz) VALUES ($1, $2)', ['now', now], function (err) {
        assert.ifError(err)
        const result = client.query(
          new pg.Query({
            name: 'get date',
            text: 'select * from date_tests where name = $1',
            values: ['now'],
          })
        )

        result.on('row', function (row) {
          const date = row.tstz
          assert.equal(date.getYear(), now.getYear())
          assert.equal(date.getMonth(), now.getMonth())
          assert.equal(date.getDate(), now.getDate())
          assert.equal(date.getHours(), now.getHours())
          assert.equal(date.getMinutes(), now.getMinutes())
          assert.equal(date.getSeconds(), now.getSeconds())
        })

        result.on('end', () => {
          client.end(cb)
        })
      })
    })
  })
})

suite.test('selecting nulls', (cb) => {
  const pool = new pg.Pool()
  pool.connect(
    assert.calls(function (err, client, done) {
      assert.ifError(err)
      client.query(
        'select null::text as res;',
        assert.calls(function (err, res) {
          assert(!err)
          assert.strictEqual(res.rows[0].res, null)
        })
      )
      client.query('select 7 <> $1::bigint as res;', [null], function (err, res) {
        assert(!err)
        assert.strictEqual(res.rows[0].res, null)
        done()
        pool.end(cb)
      })
    })
  )
})

suite.test('date range extremes', function (done) {
  const client = helper.client()
  client.query(
    'SELECT $1::text::TIMESTAMPTZ as when',
    ['2026-01-01 00:00:00 GMT'],
    assert.success(function (res) {
      assert.equal(res.rows[0].when.getFullYear(), 2026)
      client.end(done)
    })
  )
})
