'use strict'
const helper = require('../../test-helper.cjs')
const assert = require('assert')
const suite = new helper.Suite()

suite.test('JSONB type encoding and decoding', function (done) {
  const pool = new helper.pg.Pool()
  pool.connect(
    assert.success(function (client, poolDone) {
      client.query('CREATE TABLE IF NOT EXISTS stuff(spanner_pk_id BIGINT GENERATED BY DEFAULT AS IDENTITY (BIT_REVERSED_POSITIVE) PRIMARY KEY, id BIGINT, data JSONB)', function (err) {
        assert.ifError(err)
        client.query('DELETE FROM stuff', function (err) {
          assert.ifError(err)
          const value = { name: 'Brian', age: 250, alive: true, now: new Date() }
          client.query('INSERT INTO stuff (data) VALUES ($1::jsonb)', [value], function (err) {
            assert.ifError(err)
            client.query(
              'SELECT * FROM stuff',
              assert.success(function (result) {
                assert.equal(result.rows.length, 1)
                assert.equal(typeof result.rows[0].data, 'object')
                const row = result.rows[0].data
                assert.strictEqual(row.name, value.name)
                assert.strictEqual(row.age, value.age)
                assert.strictEqual(row.alive, value.alive)
                assert.equal(JSON.stringify(row.now), JSON.stringify(value.now))
                poolDone()
                pool.end(done)
              })
            )
          })
        })
      })
    })
  )
})
