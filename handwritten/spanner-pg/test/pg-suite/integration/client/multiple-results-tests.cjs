suite.test('mixed queries and statements', async function () {
  const client = new helper.Client()
  await client.connect()

  const text = `
CREATE TABLE IF NOT EXISTS weather_multi_test(spanner_pk_id BIGINT GENERATED BY DEFAULT AS IDENTITY (BIT_REVERSED_POSITIVE) PRIMARY KEY, type text);
INSERT INTO weather_multi_test(type) VALUES ('rain');
SELECT * FROM weather_multi_test;
`

  const results = await client.query(text)
  assert(Array.isArray(results))
  assert.equal(results[0].command, 'CREATE')
  assert.equal(results[1].command, 'INSERT')
  assert.equal(results[2].command, 'SELECT')

  return client.end()
})
