import * as fs from 'fs';
import * as https from 'https';
import * as path from 'path';
import * as assert from 'assert';
import {GoogleAuth, googleAuthLibrary} from 'google-gax';
import {ShowcaseServer} from 'showcase-server';
import {BigQuery} from '@google-cloud/bigquery';

/**
 * Tests Post Quantum Cryptography (PQC) using the specified CA cert and port.
 * It verifies BigQuery REST client by inspecting the negotiated TLS group.
 * @param pemPath Path to the generated CA certificate file.
 * @param port The port the TLS showcase server is listening on.
 */
async function testPqc(pemPath: string, port: number) {
  console.log('Running Post Quantum Cryptography (PQC) BigQuery Integration Tests...');

  // Verify the CA certificate file exists and is fully written
  let pemBuffer: Buffer | undefined;
  for (let i = 0; i < 15; i++) {
    if (fs.existsSync(pemPath)) {
      const tempBuffer = fs.readFileSync(pemPath);
      if (tempBuffer.length > 0 && tempBuffer.toString().includes('-----END CERTIFICATE-----')) {
        pemBuffer = tempBuffer;
        break;
      }
    }
    await new Promise(resolve => setTimeout(resolve, 1000));
  }
  if (!pemBuffer) {
    throw new Error(`CA Certificate file not found or invalid at ${pemPath}`);
  }

  // Globally intercept tls.connect for localhost connections to automatically
  // trust our autogenerated CA cert. This ensures all REST libraries (like teeny-request
  // used by @google-cloud/common) can verify the self-signed certificate seamlessly.
  const tls = require('tls');
  const originalTlsConnect = tls.connect;
  try {
    tls.connect = function (...args: any[]) {
      const options0 = args[0];
      if (typeof options0 === 'object' && options0 !== null) {
        if (options0.host === 'localhost' || options0.host === '127.0.0.1') {
          options0.ca = pemBuffer;
        }
      }
      const options2 = args[2];
      if (typeof options2 === 'object' && options2 !== null) {
        if (options2.host === 'localhost' || options2.host === '127.0.0.1') {
          options2.ca = pemBuffer;
        }
      }
      return originalTlsConnect.apply(tls, args);
    };

    // --- BigQuery PQC Test ---
    console.log('Testing PQC via BigQuery client...');

    const authCommon = new GoogleAuth({
      authClient: new googleAuthLibrary.PassThroughClient(),
    });

    const bigquery = new BigQuery({
      apiEndpoint: `localhost:${port}`,
      projectId: 'pqc-test',
      authClient: authCommon as any,
    });

    // The GAPIC showcase server enforces format checks requiring specific tokens in the
    // X-Goog-Api-Client header (e.g., 'rest/' and 'gapic/'). For REST calls made by
    // @google-cloud/common's Service/ServiceObject where headers are hardcoded, appending
    // these required tokens directly to packageJson.version serves as a clean workaround.
    (bigquery as any).packageJson.version = '8.3.1 rest/5.0.7 gapic/0.1.0';

    // Disable the prettyPrint request interceptor added by BigQuery class, as the general-purpose
    // showcase-server does not support 'prettyPrint=false' query parameter.
    bigquery.interceptors = [];

    await new Promise<void>((resolve, reject) => {
      bigquery.request(
        {
          method: 'POST',
          uri: `https://localhost:${port}/v1beta1/echo:echo`,
          json: {
            content: 'bigquery-pqc-test',
          },
          headers: {
            'x-goog-api-client': 'gl-node/22.22.1 gccl/8.3.1 rest/5.0.7 gapic/0.1.0',
          },
          agent: new https.Agent({
            ca: pemBuffer,
            keepAlive: true,
          }),
        } as any,
        (err, body, response) => {
          if (err) {
            reject(err);
          } else {
            try {
              assert.strictEqual(body.content, 'bigquery-pqc-test');
              if (!response || !response.headers) {
                throw new Error('Expected response and headers to be defined');
              }
              const group = response.headers['x-showcase-tls-group'] || (response.headers.get && response.headers.get('x-showcase-tls-group'));
              console.log(`BigQuery REST TLS negotiated group: ${group}`);
              assert.ok(group, 'Expected negotiated TLS group in BigQuery response headers');
              assert.strictEqual(group, 'X25519MLKEM768');
              resolve();
            } catch (e) {
              reject(e);
            }
          }
        }
      );
    });

    console.log('BigQuery PQC Integration Test Passed Successfully!');
  } finally {
    tls.connect = originalTlsConnect;
  }
}

/**
 * Spins up a TLS-enabled showcase server and runs the BigQuery PQC compliance tests.
 * Cleans up the generated certificate file after the tests complete.
 */
export async function runPqcBigQueryTests() {
  console.log('Starting PQC test with TLS-enabled showcase server...');
  process.env['SHOWCASE_VERSION'] = '0.41.1';
  const showcaseServerTls = new ShowcaseServer();
  const tlsPort = 7443;
  const caCertOutputFile = 'showcase.pem';
  const pemPath = path.join(process.cwd(), caCertOutputFile);

  try {
    if (fs.existsSync(pemPath)) {
      fs.unlinkSync(pemPath);
    }

    await (showcaseServerTls as any).start({
      tls: true,
      port: `:${tlsPort}`,
      caCertOutputFile: caCertOutputFile,
    });

    await testPqc(pemPath, tlsPort);
  } finally {
    try {
      showcaseServerTls.stop();
    } catch (err) {
      console.error('Failed to stop showcase server:', err);
    }
    if (fs.existsSync(pemPath)) {
      try {
        fs.unlinkSync(pemPath);
      } catch (err) {
        console.error('Failed to delete PEM file:', err);
      }
    }
  }
}
